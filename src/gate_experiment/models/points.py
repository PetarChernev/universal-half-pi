"""One operating point and collections of points to characterize."""

from __future__ import annotations

from collections.abc import Iterable, Iterator, Mapping, Sequence
from dataclasses import dataclass, field
from itertools import product
from types import MappingProxyType

from .parameters import ParameterSet, Scalar
from ..targets.base import OperationUnderTest


@dataclass(frozen=True)
class ExperimentPoint:
    """One target operation evaluated at one set of external parameters.

    Technique-internal coordinates such as tomography bases, Ramsey phases, and
    RB sequence lengths do not belong here.  They are generated by the selected
    characterization technique for this point.
    """

    point_id: str
    target: OperationUnderTest
    parameters: ParameterSet = field(default_factory=ParameterSet)
    metadata: Mapping[str, str] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.point_id:
            raise ValueError("Point IDs cannot be empty.")
        if not isinstance(self.parameters, ParameterSet):
            object.__setattr__(self, "parameters", ParameterSet(self.parameters))
        object.__setattr__(self, "metadata", MappingProxyType(dict(self.metadata)))
        self.target.validate(self.parameters)

    @property
    def resolved_parameters(self) -> ParameterSet:
        """Return validated parameters with target defaults inserted."""

        return self.target.resolve_parameters(self.parameters)


@dataclass(frozen=True)
class SweepAxis:
    """One named axis used to generate experimental points."""

    name: str
    values: tuple[Scalar, ...]
    unit: str | None = None
    description: str = ""

    def __post_init__(self) -> None:
        if not self.name:
            raise ValueError("Sweep-axis names cannot be empty.")
        if not self.values:
            raise ValueError(f"Sweep axis {self.name!r} cannot be empty.")
        object.__setattr__(self, "values", tuple(self.values))


@dataclass(frozen=True)
class PointSet(Sequence[ExperimentPoint]):
    """An ordered, immutable collection of unique experimental points."""

    points: tuple[ExperimentPoint, ...]

    def __post_init__(self) -> None:
        object.__setattr__(self, "points", tuple(self.points))
        identifiers = [point.point_id for point in self.points]
        if len(set(identifiers)) != len(identifiers):
            raise ValueError("Point IDs must be unique within a PointSet.")

    def __getitem__(self, index: int | slice) -> ExperimentPoint | Sequence[ExperimentPoint]:
        return self.points[index]

    def __len__(self) -> int:
        return len(self.points)

    def __iter__(self) -> Iterator[ExperimentPoint]:
        return iter(self.points)

    @classmethod
    def explicit(cls, points: Iterable[ExperimentPoint]) -> PointSet:
        """Create a collection from explicitly constructed points."""

        return cls(tuple(points))

    @classmethod
    def cartesian(
        cls,
        *,
        targets: Iterable[OperationUnderTest],
        axes: Iterable[SweepAxis] = (),
        fixed: Mapping[str, Scalar] | None = None,
    ) -> PointSet:
        """Create the Cartesian product of targets and sweep-axis values."""

        target_tuple = tuple(targets)
        axis_tuple = tuple(axes)
        cls._validate_generation_inputs(target_tuple, axis_tuple, fixed)
        value_products = product(*(axis.values for axis in axis_tuple)) if axis_tuple else [()]
        combinations = tuple(value_products)
        points = []
        index = 0
        for target in target_tuple:
            for values in combinations:
                parameters = dict(fixed or {})
                parameters.update({axis.name: value for axis, value in zip(axis_tuple, values, strict=True)})
                points.append(
                    ExperimentPoint(
                        point_id=f"{target.operation_id}:{index:04d}",
                        target=target,
                        parameters=ParameterSet(parameters),
                    )
                )
                index += 1
        return cls(tuple(points))

    @classmethod
    def zipped(
        cls,
        *,
        targets: Iterable[OperationUnderTest],
        axes: Iterable[SweepAxis],
        fixed: Mapping[str, Scalar] | None = None,
    ) -> PointSet:
        """Create points by pairing axis values position by position."""

        target_tuple = tuple(targets)
        axis_tuple = tuple(axes)
        cls._validate_generation_inputs(target_tuple, axis_tuple, fixed)
        if not axis_tuple:
            raise ValueError("A zipped sweep needs at least one axis.")
        lengths = {len(axis.values) for axis in axis_tuple}
        if len(lengths) != 1:
            raise ValueError("All axes in a zipped sweep must have the same length.")

        points = []
        index = 0
        for target in target_tuple:
            for values in zip(*(axis.values for axis in axis_tuple), strict=True):
                parameters = dict(fixed or {})
                parameters.update({axis.name: value for axis, value in zip(axis_tuple, values, strict=True)})
                points.append(
                    ExperimentPoint(
                        point_id=f"{target.operation_id}:{index:04d}",
                        target=target,
                        parameters=ParameterSet(parameters),
                    )
                )
                index += 1
        return cls(tuple(points))

    @classmethod
    def concatenate(cls, *point_sets: PointSet) -> PointSet:
        """Combine point collections while preserving their order."""

        return cls(tuple(point for point_set in point_sets for point in point_set))

    @staticmethod
    def _validate_generation_inputs(
        targets: tuple[OperationUnderTest, ...],
        axes: tuple[SweepAxis, ...],
        fixed: Mapping[str, Scalar] | None,
    ) -> None:
        if not targets:
            raise ValueError("At least one operation under test is required.")
        names = [axis.name for axis in axes]
        if len(set(names)) != len(names):
            raise ValueError("Sweep-axis names must be unique.")
        overlap = set(names) & set(fixed or {})
        if overlap:
            raise ValueError(f"Fixed parameters overlap sweep axes: {sorted(overlap)}.")
